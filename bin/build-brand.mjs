/**
 * Generates the MONTE3L brand pack under `source/brand/` from one geometry
 * module (`bin/lib/brand-geometry.mjs`) and the resolved colour tokens
 * (`source/lib/design-tokens.mjs`), so no logo file holds a colour the design
 * system does not.
 *
 *   node bin/build-brand.mjs                  write every file, SVG and raster
 *   node bin/build-brand.mjs --check          fail if a text file is stale or a raster is missing
 *   node bin/build-brand.mjs --social <dir>   render one 1280x640 card per repository, outside the repo
 *
 * The SVG, JSON and manifest files are plain text and are compared byte for
 * byte under `--check`. The PNG and ICO files are rendered by headless Chrome
 * and are not reproducible byte for byte, so `--check` only confirms they
 * exist; `SHA256SUMS` pins them. Set `CHROME` to a browser binary to override
 * the search. After writing, run `node bin/build-design-tokens.mjs`, because
 * `SHA256SUMS` covers everything under `source/`.
 */
import { execFileSync } from "node:child_process";
import { existsSync } from "node:fs";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import process from "node:process";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  flattenColors,
  loadDesignSystem,
  resolveTheme,
} from "../source/lib/design-tokens.mjs";
import {
  cardSvg,
  lockupSvg,
  symbolBody,
  symbolSvg,
  wordmarkSvg,
} from "./lib/brand-geometry.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "source/brand");

// REUSE-IgnoreStart -- the banner below is the SPDX tag of the generated files, not this file's own
const SPDX = `<!--
  SPDX-FileCopyrightText: 2026 Enrico Lionello (enri3l), Giulia Montevecchi (giulmonte), monte3l
  SPDX-License-Identifier: LicenseRef-MONTE3L-Brand
  GENERATED by bin/build-brand.mjs in m3l-design. Do not edit by hand.
-->
`;
// REUSE-IgnoreEnd

const FONT_STACK = `'Atkinson Hyperlegible Next', system-ui, sans-serif`;
const ORG_TAGLINE = "Open-source tooling for TypeScript projects and Claude Code.";

class BrandError extends Error {
  constructor(message, options) {
    super(message, options);
    this.name = "BrandError";
  }
}

/** The colours the brand uses, by role, resolved from the design tokens for both themes. */
async function loadColours() {
  const system = await loadDesignSystem(path.join(root, "source/dtcg"));
  const pick = (theme) => {
    const all = new Map(
      flattenColors(resolveTheme(system, theme, "default")).map(({ name, value }) => [name, value]),
    );
    const get = (name) => {
      const value = all.get(name);
      if (value === undefined) throw new BrandError(`token ${name} is not defined in the ${theme} theme`);
      return value;
    };
    return {
      ink: get("color-text-primary"),
      secondary: get("color-text-secondary"),
      wine: get("color-accent-default"),
      ground: get("color-surface-default"),
    };
  };
  return { light: pick("light"), dark: pick("dark") };
}

const fill = (value) => `fill="${value}"`;

/** Every text file of the pack, as `[path relative to source/brand, content]`. */
function textFiles({ light, dark }) {
  const files = new Map();
  const themes = { light, dark, mono: { ink: "currentColor", wine: "currentColor" } };
  for (const [name, c] of Object.entries(themes)) {
    const attrs = { eAttr: fill(c.ink), wAttr: fill(c.wine) };
    const words = { fill: fill(c.ink), accent: fill(c.wine) };
    files.set(`logo/symbol-${name}.svg`, SPDX + symbolSvg({ ...attrs }));
    files.set(`logo/wordmark-${name}.svg`, SPDX + wordmarkSvg({ ...words }));
    files.set(`logo/lockup-${name}.svg`, SPDX + lockupSvg({ ...attrs, ...words }));
  }

  // The favicon is the only file that adapts to the viewer's theme itself.
  const style = `
<style>.e{fill:${light.ink}}.w{fill:${light.wine}}@media (prefers-color-scheme:dark){.e{fill:${dark.ink}}.w{fill:${dark.wine}}}</style>`;
  files.set(
    "favicon/favicon.svg",
    SPDX + symbolSvg({ id: "m3l-favicon", variant: "small", eAttr: 'class="e"', wAttr: 'class="w"', style }),
  );
  files.set(
    "favicon/icon-monochrome.svg",
    SPDX + symbolSvg({ id: "m3l-mono", scale: 0.8, eAttr: 'fill="#000"', wAttr: 'fill="#000"' }),
  );
  files.set(
    "favicon/site.webmanifest",
    `${JSON.stringify(
      {
        name: "MONTE3L",
        short_name: "MONTE3L",
        theme_color: light.wine,
        background_color: light.ground,
        icons: [
          { src: "icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
          { src: "icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
          { src: "icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
          { src: "icon-monochrome.svg", sizes: "any", type: "image/svg+xml", purpose: "monochrome" },
        ],
      },
      null,
      2,
    )}\n`,
  );

  for (const [file, width, height] of [
    ["social/social-preview.svg", 1280, 640],
    ["social/og-image.svg", 1200, 630],
  ]) {
    files.set(
      file,
      SPDX +
        cardSvg({ width, height, name: "monte3l", tagline: ORG_TAGLINE, c: light, id: "m3l-card", fontFamily: FONT_STACK }),
    );
  }
  return files;
}

function findChrome() {
  const candidates = [
    process.env.CHROME,
    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
    "/Applications/Chromium.app/Contents/MacOS/Chromium",
    "/usr/bin/google-chrome",
    "/usr/bin/chromium",
    "/usr/bin/chromium-browser",
  ].filter(Boolean);
  const found = candidates.find((candidate) => existsSync(candidate));
  if (!found) {
    throw new BrandError("no Chrome or Chromium found: install one or set CHROME to its binary");
  }
  return found;
}

/**
 * Renders an inline SVG to a transparent PNG with headless Chrome. `body` is
 * the markup of a page that holds nothing else; `fontCss` is optional CSS.
 */
async function renderPng(chrome, { body, width, height, out, fontCss = "" }) {
  const dir = await mkdtemp(path.join(tmpdir(), "m3l-brand-"));
  try {
    const page = path.join(dir, "page.html");
    await writeFile(
      page,
      `<!doctype html><meta charset="utf-8"><style>${fontCss}html,body{margin:0;background:transparent}svg{display:block;width:${width}px;height:${height}px}</style>${body}`,
    );
    await mkdir(path.dirname(out), { recursive: true });
    // Remove the old file first, so a Chrome that exits 0 without writing cannot pass on a stale one.
    await rm(out, { force: true });
    try {
      execFileSync(
        chrome,
        [
          "--headless",
          "--disable-gpu",
          "--hide-scrollbars",
          "--force-device-scale-factor=1",
          "--default-background-color=00000000",
          `--window-size=${width},${height}`,
          `--screenshot=${out}`,
          pathToFileURL(page).href,
        ],
        { stdio: "pipe", timeout: 60_000 },
      );
    } catch (cause) {
      const detail = String(cause.stderr ?? "").trim().split("\n").at(-1) || cause.message.split("\n")[0];
      throw new BrandError(`Chrome failed to render ${path.basename(out)}: ${detail}`);
    }
    if (!existsSync(out)) throw new BrandError(`Chrome produced no file for ${path.relative(root, out)}`);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

const strip = (svg) => svg.replace(SPDX, "").trim();

/** A symbol on a solid square (or rounded square) of the accent colour, for icons and the avatar. */
function badge({ c, dark, size, scale, variant = "large", rounded, id }) {
  const radius = rounded ? size * 0.22 : 0;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1000 1000">
<rect width="1000" height="1000" rx="${radius * (1000 / size)}" fill="${c.wine}"/>
${symbolBody({ id, variant, scale, eAttr: fill(c.ground), wAttr: fill(dark.wine) })}
</svg>`;
}

/** Packs PNG frames into an ICO: a 6-byte header, a 16-byte entry per image, then the images. */
function packIco(frames) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(frames.length, 4);
  const entries = Buffer.alloc(16 * frames.length);
  let offset = header.length + entries.length;
  frames.forEach(({ size, data }, i) => {
    const at = i * 16;
    entries.writeUInt8(size === 256 ? 0 : size, at);
    entries.writeUInt8(size === 256 ? 0 : size, at + 1);
    entries.writeUInt16LE(1, at + 4);
    entries.writeUInt16LE(32, at + 6);
    entries.writeUInt32LE(data.length, at + 8);
    entries.writeUInt32LE(offset, at + 12);
    offset += data.length;
  });
  return Buffer.concat([header, entries, ...frames.map((f) => f.data)]);
}

/** The sans font as an inline `@font-face`, so a card renders in it with no file access or load race. */
async function fonts() {
  const file = path.join(root, "source/fonts/atkinson-hyperlegible-next-latin-wght-normal.woff2");
  const data = (await readFile(file)).toString("base64");
  return `@font-face{font-family:"Atkinson Hyperlegible Next";src:url("data:font/woff2;base64,${data}") format("woff2");font-weight:200 800}`;
}

/** Every raster of the pack: `[path relative to source/brand, render]`. */
function rasterJobs(colours, texts, fontCss = "") {
  const { light, dark } = colours;
  const art = (opts) => badge({ c: light, dark, ...opts });
  const sq = (size, scale, extra = {}) => ({
    body: art({ size, scale, id: "m3l-r", ...extra }),
    width: size,
    height: size,
  });
  return [
    ["favicon/apple-touch-icon.png", sq(180, 0.9)],
    ["favicon/icon-192.png", sq(192, 0.84, { rounded: true })],
    ["favicon/icon-512.png", sq(512, 0.84, { rounded: true })],
    ["favicon/icon-maskable-512.png", sq(512, 0.8)],
    ["github/avatar.png", sq(500, 0.8)],
    ...[16, 32, 48].map((size) => [
      `ico-frame-${size}`,
      { ...sq(size, 0.88, { variant: "small", rounded: true }), temp: true },
    ]),
    ["social/social-preview.png", { body: strip(texts.get("social/social-preview.svg")), width: 1280, height: 640, fontCss }],
    ["social/og-image.png", { body: strip(texts.get("social/og-image.svg")), width: 1200, height: 630, fontCss }],
  ];
}

async function writeAll(colours) {
  // Find Chrome before touching any file, so a machine without one cannot leave
  // new SVGs next to old PNGs.
  const chrome = findChrome();
  const texts = textFiles(colours);
  for (const [rel, content] of texts) {
    await mkdir(path.dirname(path.join(outDir, rel)), { recursive: true });
    await writeFile(path.join(outDir, rel), content, "utf8");
    console.log(`wrote source/brand/${rel}`);
  }
  const scratch = await mkdtemp(path.join(tmpdir(), "m3l-ico-"));
  try {
    const frames = [];
    for (const [rel, job] of rasterJobs(colours, texts, await fonts())) {
      if (job.temp) {
        const out = path.join(scratch, `${rel}.png`);
        await renderPng(chrome, { ...job, out });
        frames.push({ size: job.width, data: await readFile(out) });
      } else {
        await renderPng(chrome, { ...job, out: path.join(outDir, rel) });
        console.log(`wrote source/brand/${rel}`);
      }
    }
    await writeFile(path.join(outDir, "favicon/favicon.ico"), packIco(frames));
    console.log("wrote source/brand/favicon/favicon.ico");
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }
}

async function check(colours) {
  let current = true;
  for (const [rel, content] of textFiles(colours)) {
    let existing = null;
    try {
      existing = await readFile(path.join(outDir, rel), "utf8");
    } catch (cause) {
      if (cause.code !== "ENOENT") throw cause;
    }
    if (existing !== content) {
      console.error(`fail  source/brand/${rel} is out of date -- run \`node bin/build-brand.mjs\` and commit the result`);
      current = false;
    }
  }
  const rasters = [
    "favicon/favicon.ico",
    ...rasterJobs(colours, textFiles(colours)).map(([rel]) => rel).filter((rel) => !rel.startsWith("ico-frame")),
  ];
  for (const rel of rasters) {
    if (!existsSync(path.join(outDir, rel))) {
      console.error(`fail  source/brand/${rel} is missing -- run \`node bin/build-brand.mjs\``);
      current = false;
    }
  }
  if (current) console.log("  ok  source/brand is current");
  return current;
}

/** Description of a repository from `gh`, or the org tagline when it has none or `gh` cannot say. */
function describeRepo(repo) {
  try {
    const text = execFileSync("gh", ["repo", "view", `monte3l/${repo}`, "--json", "description", "-q", ".description"], {
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
      timeout: 30_000,
    }).trim();
    return text || ORG_TAGLINE;
  } catch (cause) {
    console.warn(`warn  could not read the description of monte3l/${repo} (${cause.message.split("\n")[0]}); using the org tagline`);
    return ORG_TAGLINE;
  }
}

async function social(colours, dir, projectsFile) {
  let projects;
  try {
    projects = JSON.parse(await readFile(projectsFile, "utf8"));
  } catch (cause) {
    throw new BrandError(`cannot read ${projectsFile}: ${cause.message}`);
  }
  if (!Array.isArray(projects) || projects.some((p) => typeof p?.repo !== "string" || !/^[\w.-]+$/.test(p.repo) || p.repo.includes(".."))) {
    throw new BrandError(`${projectsFile} must be an array of { "repo": "<name>" } with plain repository names`);
  }
  const chrome = findChrome();
  const fontCss = await fonts();
  await mkdir(dir, { recursive: true });
  for (const { repo } of projects) {
    const svg = cardSvg({
      width: 1280,
      height: 640,
      name: repo,
      tagline: describeRepo(repo),
      c: colours.light,
      id: "m3l-card",
      fontFamily: FONT_STACK,
    });
    const out = path.join(dir, `${repo.replace(/^\./, "dot-")}.png`);
    await renderPng(chrome, { body: svg, width: 1280, height: 640, out, fontCss });
    console.log(`wrote ${out}`);
  }
}

function argValue(flag) {
  const i = process.argv.indexOf(flag);
  if (i === -1) return null;
  const value = process.argv[i + 1];
  if (!value || value.startsWith("--")) throw new BrandError(`${flag} needs a value`);
  return value;
}

const FLAGS = new Set(["--check", "--social", "--projects"]);

/** Rejects an unknown flag or a mix of modes, so a typo cannot rewrite every raster. */
function validateArgs(args) {
  const flags = args.filter((arg) => arg.startsWith("--"));
  const unknown = flags.filter((flag) => !FLAGS.has(flag));
  if (unknown.length > 0) throw new BrandError(`unknown option ${unknown.join(", ")} (use --check or --social <dir> [--projects <file>])`);
  if (flags.includes("--check") && flags.includes("--social")) throw new BrandError("--check and --social cannot be combined");
  if (flags.includes("--projects") && !flags.includes("--social")) throw new BrandError("--projects only applies with --social");
  const positional = args.filter((arg, i) => !arg.startsWith("--") && !FLAGS.has(args[i - 1]));
  if (positional.length > 0) throw new BrandError(`unexpected argument ${positional[0]}`);
}

async function main() {
  validateArgs(process.argv.slice(2));
  const colours = await loadColours();
  const socialDir = argValue("--social");
  if (socialDir) {
    const projects = argValue("--projects") ?? path.resolve(root, "../.github/blueprint/projects.json");
    await social(colours, path.resolve(socialDir), projects);
  } else if (process.argv.includes("--check")) {
    if (!(await check(colours))) process.exitCode = 1;
  } else {
    await writeAll(colours);
  }
}

try {
  await main();
} catch (error) {
  if (!(error instanceof BrandError)) throw error;
  console.error(`error ${error.message}${error.cause ? ` (${error.cause.message.split("\n")[0]})` : ""}`);
  process.exitCode = 2;
}
